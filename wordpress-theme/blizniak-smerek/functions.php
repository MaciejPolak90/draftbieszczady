}
add_action( 'after_setup_theme', 'bws_theme_setup' );

/**
 * Helper to pick latest hashed asset generated by Vite.
 *
 * @param string $pattern Glob pattern relative to /assets.
 */
function bws_find_asset( $pattern ) {
	$files = glob( BWS_THEME_DIR . '/assets/' . $pattern );

	if ( empty( $files ) ) {
		return null;
	}

	usort(
		$files,
		static function ( $a, $b ) {
			return filemtime( $b ) <=> filemtime( $a );
		}
	);

	return basename( $files[0] );
}

/**
 * Enqueue compiled CSS/JS and theme helpers.
 */
function bws_enqueue_assets() {
	$css = bws_find_asset( 'index-*.css' );
	if ( $css ) {
		$css_path = BWS_THEME_DIR . '/assets/' . $css;
		wp_enqueue_style( 'bws-main', BWS_THEME_URI . '/assets/' . $css, array(), filemtime( $css_path ) );
	}

	$custom_css = BWS_THEME_DIR . '/assets/css/theme.css';
	if ( file_exists( $custom_css ) ) {
		wp_enqueue_style( 'bws-theme', BWS_THEME_URI . '/assets/css/theme.css', array( 'bws-main' ), filemtime( $custom_css ) );
	}

	$js = bws_find_asset( 'index-*.js' );
	if ( $js ) {
		$js_path = BWS_THEME_DIR . '/assets/' . $js;
		wp_enqueue_script( 'bws-main', BWS_THEME_URI . '/assets/' . $js, array(), filemtime( $js_path ), true );
		wp_script_add_data( 'bws-main', 'defer', true );
	}

	$theme_js = BWS_THEME_DIR . '/assets/js/theme.js';
	if ( file_exists( $theme_js ) ) {
		wp_enqueue_script( 'bws-theme', BWS_THEME_URI . '/assets/js/theme.js', array(), filemtime( $theme_js ), true );
		wp_script_add_data( 'bws-theme', 'defer', true );
		wp_localize_script(
			'bws-theme',
			'bwsTheme',
			array(
				'headerOffset'   => 96,
				'scrollDuration' => 400,
				'contactAnchor'  => '#kontakt',
			)
		);
	}
}
add_action( 'wp_enqueue_scripts', 'bws_enqueue_assets' );

