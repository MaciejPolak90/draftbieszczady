/**
 * Seed default gallery categories used by filters.
 */
function bws_seed_gallery_terms() {
	$terms = array(
		'salon'    => 'Salon i kominek',
		'kuchnia'  => 'Kuchnia i jadalnia',
		'pokoje'   => 'Pokoje',
		'lazienki' => 'Łazienki',
		'altana'   => 'Altana i grill',
		'okolica'  => 'Okolica i szlaki',
		'taras'    => 'Taras (wkrótce)',
	);

	foreach ( $terms as $slug => $label ) {
		if ( ! term_exists( $slug, 'bs_photo_category' ) ) {
			wp_insert_term(
				$label,
				'bs_photo_category',
				array(
					'slug' => $slug,
				)
			);
		}
	}
}
add_action( 'after_switch_theme', 'bws_seed_gallery_terms' );

/**
 * Contact form handler: nonce + honeypot + wp_mail.
 */
function bws_handle_contact_form() {
	if ( ! is_front_page() || 'POST' !== $_SERVER['REQUEST_METHOD'] ) {
		return;
	}

	$redirect = get_option( 'page_on_front' ) ? get_permalink( (int) get_option( 'page_on_front' ) ) : home_url( '/' );
	$redirect = add_query_arg( 'sent', '0', $redirect );

	if ( empty( $_POST['bws_contact_nonce'] ) || ! wp_verify_nonce( wp_unslash( $_POST['bws_contact_nonce'] ), 'bws_contact_form' ) ) {
		wp_safe_redirect( $redirect );
		exit;
	}

	$honeypot  = ! empty( $_POST['bws_hp'] );
	$name      = isset( $_POST['bws_name'] ) ? sanitize_text_field( wp_unslash( $_POST['bws_name'] ) ) : '';
	$phone     = isset( $_POST['bws_phone'] ) ? sanitize_text_field( wp_unslash( $_POST['bws_phone'] ) ) : '';
	$date_from = isset( $_POST['bws_date_from'] ) ? sanitize_text_field( wp_unslash( $_POST['bws_date_from'] ) ) : '';
	$date_to   = isset( $_POST['bws_date_to'] ) ? sanitize_text_field( wp_unslash( $_POST['bws_date_to'] ) ) : '';
	$guests    = isset( $_POST['bws_guests'] ) ? sanitize_text_field( wp_unslash( $_POST['bws_guests'] ) ) : '';
	$has_pet   = ! empty( $_POST['bws_pet'] );
	$message   = isset( $_POST['bws_message'] ) ? wp_kses_post( wp_unslash( $_POST['bws_message'] ) ) : '';

	if ( $honeypot || empty( $name ) || empty( $phone ) || empty( $date_from ) || empty( $date_to ) || empty( $guests ) ) {
		wp_safe_redirect( $redirect );
		exit;
	}

	$brand   = bws_get_mod( 'brand_name', 'Bliźniak w Smereku' );
	$subject = sprintf( 'Zapytanie z %s', $brand );

	$body  = "Imię: {$name}\n";
	$body .= "Telefon: {$phone}\n";
	$body .= "Termin: {$date_from} - {$date_to}\n";
	$body .= "Liczba osób: {$guests}\n";
	$body .= 'Zwierzę: ' . ( $has_pet ? 'tak' : 'nie' ) . "\n\n";
	if ( ! empty( $message ) ) {
		$body .= "Wiadomość:\n{$message}\n\n";
	}
	$body .= 'Wysłane ze strony: ' . home_url();

	$sent = wp_mail( get_option( 'admin_email' ), $subject, $body );

	$redirect = add_query_arg( 'sent', $sent ? '1' : '0', $redirect );
	wp_safe_redirect( $redirect );
	exit;
}
add_action( 'template_redirect', 'bws_handle_contact_form' );
